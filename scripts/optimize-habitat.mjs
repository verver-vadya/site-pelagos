import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {dedup,prune,weld,simplify,textureCompress} from '@gltf-transform/functions';
import {MeshoptSimplifier} from 'meshoptimizer';
import sharp from 'sharp';
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS);
await MeshoptSimplifier.ready;
const document=await io.read('.check/model-sources/coast-rocks/coast_rocks_05.gltf');
await document.transform(dedup(),prune(),weld(),simplify({simplifier:MeshoptSimplifier,ratio:.045,error:.002}),textureCompress({encoder:sharp,targetFormat:'webp',resize:[1024,1024],quality:90}));
document.getRoot().setExtras({source:'https://polyhaven.com/a/coast_rocks_05',author:'Rob Tuytel',license:'CC0-1.0',modifications:'Mesh simplified; PBR textures converted to 1K WebP. Submerged lighting applied at runtime.'});
await io.write('public/models/coast-rocks.glb',document);
for(const mesh of document.getRoot().listMeshes())for(const primitive of mesh.listPrimitives())console.log(mesh.getName(),primitive.getAttribute('POSITION').getCount(),'vertices');
